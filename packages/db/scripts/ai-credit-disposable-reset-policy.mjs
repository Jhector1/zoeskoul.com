/** Offline-safe policy shared by preview/apply. No billing runtime branch. */
import { createHash } from 'node:crypto';

export const CREDIT_TABLES = Object.freeze([
  'AiCreditResultJournal',
  'AiCreditReconciliationEvidence',
  'AiCreditReconciliationEvent',
  'AiCreditReconciliationCase',
  'AiCreditProviderRequest',
  'AiCreditLedgerEntry',
  'AiCreditReservationAllocation',
  'AiCreditReservation',
  'AiCreditPaymentRiskEvent',
  'AiCreditPaymentReversalSnapshot',
  'AiCreditLot',
  'AiCreditWallet',
  'ZoeBuildAiCreditCheckoutAttempt',
]);

export const ATTEST = 'I_VERIFIED_THIS_DATABASE_CONTAINS_ONLY_DISPOSABLE_TEST_BILLING_DATA';
export const CONFIRM = 'RESET_ONLY_DISPOSABLE_AI_CREDIT_DOMAIN';
// Payment-risk records can also be generated by Stripe TEST refunds/disputes.
// They are not proof of a live charge. The operator must independently verify
// test-only provenance before authorizing their disposal.
export const RISK_TEST_ATTEST = 'I_INDEPENDENTLY_VERIFIED_ALL_PAYMENT_RISK_RECORDS_ARE_TEST_ONLY';
export const NO_LIVE_FUNDS_ATTEST = 'I_VERIFIED_NO_REAL_PAYMENTS_OR_CUSTOMER_CREDITS_ARE_IN_THIS_DATABASE';

export function readFlag(argv, name) {
  const at = argv.indexOf(name);
  if (at === -1) return null;
  if (at + 1 >= argv.length || argv[at + 1].startsWith('--')) throw Error(`MISSING_${name.slice(2).replaceAll('-','_').toUpperCase()}`);
  if (argv.indexOf(name, at + 1) !== -1) throw Error('DUPLICATE_FLAG');
  return argv[at + 1];
}

/** Database host/name matching protects against mistakes, NOT tunneled production. */
export function assertTarget({url, expectedHost, expectedDatabase, expectedSchema}) {
  if (!url || !expectedHost || !expectedDatabase || !expectedSchema) throw Error('EXPLICIT_DATABASE_TARGET_REQUIRED');
  let u;
  try { u = new URL(url); } catch { throw Error('DATABASE_URL_INVALID'); }
  if (!['postgresql:', 'postgres:'].includes(u.protocol)) throw Error('POSTGRES_REQUIRED');
  const database = decodeURIComponent(u.pathname.slice(1));
  const schema = u.searchParams.get('schema') || 'public';
  if (!database || u.hostname !== expectedHost || database !== expectedDatabase || schema !== expectedSchema)
    throw Error('DATABASE_TARGET_MISMATCH');
  // Loopback may be a tunnel. Separate independent attestation is ALWAYS required.
  if (!['localhost','127.0.0.1','::1'].includes(u.hostname)) throw Error('NON_LOOPBACK_RESET_REFUSED');
  return {host:u.hostname, database, schema};
}

export function assertApplyAuthorization({argv, fingerprint, paymentRiskRecords = 0}) {
  if (readFlag(argv,'--attest') !== ATTEST || readFlag(argv,'--confirm') !== CONFIRM ||
      readFlag(argv,'--fingerprint') !== fingerprint || !argv.includes('--application-stopped'))
    throw Error('APPLY_AUTHORIZATION_INCOMPLETE');
  if (!Number.isSafeInteger(paymentRiskRecords) || paymentRiskRecords < 0)
    throw Error('PAYMENT_RISK_COUNT_INVALID');
  if (paymentRiskRecords > 0 &&
      (readFlag(argv, '--attest-test-only-risk') !== RISK_TEST_ATTEST ||
       readFlag(argv, '--attest-no-live-funds') !== NO_LIVE_FUNDS_ATTEST))
    throw Error('PAYMENT_RISK_TEST_ONLY_ATTESTATION_REQUIRED');
}

export function snapshotFingerprint({identity, rows, liveStripeEvents, nonTestSignal}) {
  if (!identity || !Array.isArray(rows) || rows.length !== CREDIT_TABLES.length ||
      !Number.isSafeInteger(liveStripeEvents) || liveStripeEvents < 0 ||
      !Number.isSafeInteger(nonTestSignal) || nonTestSignal < 0) throw Error('SNAPSHOT_INVALID');
  for (let i=0; i<CREDIT_TABLES.length; i++) {
    const row = rows[i];
    if (row.table !== CREDIT_TABLES[i] || !Number.isSafeInteger(row.count) || row.count < 0 ||
        typeof row.digest !== 'string' || !/^[a-f0-9]{32}$/.test(row.digest)) throw Error('SNAPSHOT_INVALID');
  }
  return createHash('sha256').update(JSON.stringify({version:1,identity,rows,liveStripeEvents,nonTestSignal})).digest('hex');
}

export function assertDisposableSignals({liveStripeEvents, nonTestSignal, riskRecordsAttested = false}) {
  if (liveStripeEvents !== 0) throw Error('LIVE_STRIPE_EVENTS_REFUSE_RESET');
  // Risk/reversal history is not itself evidence of live payment: test Stripe
  // refunds and disputes produce the same table rows. Fail closed unless the
  // exceptional test-fixture attestation has been independently provided.
  if (nonTestSignal !== 0 && !riskRecordsAttested)
    throw Error('PAYMENT_RISK_TEST_ONLY_ATTESTATION_REQUIRED');
}
