"use client";

type CommerceProject = Readonly<{
  title: string;
  stackId: string | null;
}>;

export default function CommerceWorkspacePanel(props: {
  project: CommerceProject;
  candidateHostname?: string | null;
}) {
  if (
    props.project.stackId !==
      "commerce-static-v1" &&
    props.project.stackId !==
      "commerce-react-vite-v1"
  ) {
    return null;
  }

  return (
    <div className="zb-commerce-workspace">
      <div className="zb-commerce-heading">
        <div>
          <div className="zb-commerce-kicker">
            Commerce
          </div>

          <h2>
            {props.project.title}
          </h2>

          <p>
            Your storefront design and trusted commerce
            foundation are ready. Connect a commerce provider
            before using live catalog, cart, checkout, orders,
            or payments.
          </p>
        </div>

        <span className="zb-commerce-status zb-commerce-status-off">
          Not connected
        </span>
      </div>

      {props.candidateHostname ? (
        <div className="zb-commerce-candidate">
          <strong>
            Ready to connect:
          </strong>{" "}
          {props.candidateHostname}
          <div>
            The address is validated, but no provider
            connection or credential has been created yet.
          </div>
        </div>
      ) : null}

      <div className="zb-commerce-grid">
        <section className="zb-commerce-card">
          <span>
            Products &amp; inventory
          </span>

          <strong>
            Managed provider
          </strong>

          <p>
            Live catalog data appears after a store is
            connected.
          </p>
        </section>

        <section className="zb-commerce-card">
          <span>
            Cart
          </span>

          <strong>
            Foundation ready
          </strong>

          <p>
            Cart behavior is owned by the trusted storefront
            foundation, not generated by AI.
          </p>
        </section>

        <section className="zb-commerce-card">
          <span>
            Checkout
          </span>

          <strong>
            Provider-hosted
          </strong>

          <p>
            Customers are handed to the connected commerce
            provider for checkout.
          </p>
        </section>

        <section className="zb-commerce-card">
          <span>
            Payments
          </span>

          <strong>
            Configure with provider
          </strong>

          <p>
            ZoeBuild does not collect raw payment-card
            credentials in generated source.
          </p>
        </section>

        <section className="zb-commerce-card">
          <span>
            Orders
          </span>

          <strong>
            Available after connection
          </strong>

          <p>
            No fake order totals or duplicated order database
            are created before provider binding.
          </p>
        </section>

        <section className="zb-commerce-card">
          <span>
            Customer accounts
          </span>

          <strong>
            Not enabled
          </strong>

          <p>
            The baseline storefront intentionally fails
            closed until the dedicated customer-account
            boundary is implemented.
          </p>
        </section>
      </div>

      <div className="zb-commerce-security">
        <strong>
          Commerce security boundary
        </strong>

        <span>
          Provider credentials belong in ZoeBuild resource
          bindings and secret references, never in generated
          storefront files.
        </span>
      </div>
    </div>
  );
}
